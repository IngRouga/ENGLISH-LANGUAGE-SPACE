const I18N = (() => {
  let lang = "fr";
  try { lang = localStorage.getItem("els-lang") || (navigator.language || "fr").slice(0, 2); } catch (e) {}
  if (lang !== "en") lang = "fr";
  const textNodes = [], attrs = [];
  const collect = () => {
    const w = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
      acceptNode: n => n.parentElement.closest("script,style,svg,#booksGrid,#testBody,#rotator") ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT
    });
    let n;
    while ((n = w.nextNode())) {
      const k = n.nodeValue.trim();
      if (EN[k]) textNodes.push([n, n.nodeValue, n.nodeValue.replace(k, EN[k])]);
    }
    document.querySelectorAll("[placeholder],[alt],[aria-label]").forEach(el =>
      ["placeholder", "alt", "aria-label"].forEach(a => { const v = el.getAttribute(a); if (v && EN[v]) attrs.push([el, a, v, EN[v]]); }));
  };
  const apply = l => {
    lang = l;
    try { localStorage.setItem("els-lang", l); } catch (e) {}
    document.documentElement.lang = l;
    textNodes.forEach(([n, fr, en]) => n.nodeValue = l === "en" ? en : fr);
    attrs.forEach(([el, a, fr, en]) => el.setAttribute(a, l === "en" ? en : fr));
    document.querySelectorAll(".lang button").forEach(b => b.classList.toggle("on", b.dataset.lang === l));
    document.dispatchEvent(new CustomEvent("langchange", { detail: l }));
  };
  return { collect, apply, get lang() { return lang; }, s: k => STR[lang][k] };
})();
